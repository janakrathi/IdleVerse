// Copies the line-art pictures IdleVerse uses out of the Lucide icon set (ISC licence)
// into src/renderer/icons.js, so the app doesn't ship the whole 57 MB package.
// Usage: node scripts/build-icons.js <path to node_modules/lucide-static>
const fs = require('fs');
const path = require('path');

const ICONS = [
  'heart', 'heart-crack', 'flame', 'moon', 'sun', 'sunset', 'star', 'sparkles', 'music', 'music-2',
  'car', 'route', 'banknote', 'gem', 'crown', 'cloud-rain', 'cloud-lightning', 'droplets', 'zap', 'waves',
  'eye', 'phone', 'clock', 'plane', 'house', 'key', 'flower', 'camera', 'ghost', 'skull', 'building-2',
  'globe', 'mountain', 'wine', 'smile', 'hand', 'swords', 'mic', 'headphones', 'snowflake', 'cloud',
  'rocket', 'infinity', 'trees', 'bird', 'coffee', 'wind', 'umbrella', 'footprints', 'lock', 'bed',
  'book-open', 'party-popper', 'map-pin', 'hourglass', 'feather', 'shell', 'anchor', 'moon-star', 'flower-2'
];

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-icons.js <node_modules/lucide-static>'); process.exit(1); }

const out = {};
const missing = [];
for (const name of ICONS) {
  const file = path.join(dir, 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) { missing.push(name); continue; }
  const svg = fs.readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s*\n\s*/g, '');
  out[name] = inner;
}
const licence = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').trim().split('\n').map((l) => ` * ${l}`.trimEnd()).join('\n');

const js = `/*
 * Line-art pictures shown next to matching lyrics.
 * From Lucide (https://lucide.dev), generated by scripts/build-icons.js. Licence:
 *
${licence}
 */
window.ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}')};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'icons.js'), js);
console.log(`wrote ${Object.keys(out).length} icons${missing.length ? `; missing: ${missing.join(', ')}` : ''}`);
